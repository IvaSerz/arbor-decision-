import {packager} from '@electron/packager';
import {mkdir,copyFile,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const platform=process.argv[2],arch=process.argv[3];
const {version}=JSON.parse(await readFile('package.json','utf8'));
const macSigning=platform==='darwin'&&process.platform==='darwin'?{identity:'-',identityValidation:false,preAutoEntitlements:false,optionsForFile:()=>({hardenedRuntime:false,entitlements:['com.apple.security.cs.allow-jit']})}:false;
if(!['win32','darwin','linux'].includes(platform)||!['x64','arm64'].includes(arch))throw Error('Usage: node scripts/desktop-package.mjs win32|darwin|linux x64|arm64');
await mkdir('desktop-stage',{recursive:true});
await copyFile('desktop/main.cjs','desktop-stage/main.cjs');
let html=await readFile('portable/Arbor.html','utf8');
const script=html.match(/<script type="module">([\s\S]*)<\/script>/)[1];
const hash=createHash('sha256').update(script).digest('base64');
const csp=`default-src 'none'; script-src 'sha256-${hash}' 'wasm-unsafe-eval'; style-src 'unsafe-inline'; img-src data:; worker-src blob:; connect-src 'none'; object-src 'none'; base-uri 'none'`;
html=html.replace('<meta charset="utf-8">',`<meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}">`);
await writeFile('desktop-stage/Arbor.html',html);
await writeFile('desktop-stage/package.json',JSON.stringify({name:'arbor-decision',productName:'Arbor',version,description:'Offline decision support',author:'Arbor Laboratory',main:'main.cjs'}));
const result=await packager({dir:'desktop-stage',out:'release',platform,arch,name:'Arbor',appVersion:version,appBundleId:'lab.arbor.decision',overwrite:true,asar:true,prune:true,osxSign:macSigning,osxNotarize:false});
console.log(result.join('\n'));
